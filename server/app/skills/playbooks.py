"""Подсказки агенту по рабочим системам клиентов.

Каждый плейбук попадает в системный промпт шага, когда запрос или текущий адрес
браузера относится к системе. Текст короткий: что где лежит, как ходить по
интерфейсу, что опасно. Адреса разделов — ориентир; если страница не открылась,
агент идёт через меню.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class LoginForm:
    """Как выглядит вход. Селекторы — первые кандидаты, агент сверяется со скриншотом."""

    username_selectors: tuple[str, ...]
    password_selectors: tuple[str, ...]
    submit_selectors: tuple[str, ...]
    two_step: bool = False
    next_selectors: tuple[str, ...] = ()


@dataclass(frozen=True)
class Playbook:
    id: str
    name: str
    keywords: tuple[str, ...]  # регулярки, ищутся с начала слова
    host_suffixes: tuple[str, ...]
    url_markers: tuple[str, ...]
    guide: str
    login: LoginForm
    confirm_before: tuple[str, ...] = field(default=())
    # Чужие домены, где система сама показывает форму входа (единый вход облака).
    auth_hosts: tuple[str, ...] = field(default=())


